func TestWatchFeedETagAnd304(t *testing.T) {
	_, ts := newWatchFeedServer(t, watchFeedCatalog())
	path := "/api/v1/watch/feed.atom?s=the-stormlight-archive"
	resp, _ := watchFeedResponse(t, ts, path)
	etag := resp.Header.Get("ETag")
	if etag == "" {
		t.Fatal("feed has no ETag")
	}
	req, err := http.NewRequest(http.MethodGet, ts.URL+path, nil)
	if err != nil {
		t.Fatal(err)
	}
	req.Header.Set("If-None-Match", etag)
	conditional, err := http.DefaultClient.Do(req)
	if err != nil {
		t.Fatal(err)
	}
	defer func() { _ = conditional.Body.Close() }()
	if conditional.StatusCode != http.StatusNotModified {
		t.Errorf("conditional status = %d, want 304", conditional.StatusCode)
	}
	if conditional.Header.Get("Cache-Control") != watchFeedMaxAge {
		t.Errorf("304 Cache-Control = %q", conditional.Header.Get("Cache-Control"))
	}

	other, _ := watchFeedResponse(t, ts, path+"&window=30")
	if other.Header.Get("ETag") == etag {
		t.Errorf("raw window parameter did not change ETag %q", etag)
	}
	jsonResp, _ := watchFeedResponse(t, ts, strings.Replace(path, ".atom", ".json", 1))
	if jsonResp.Header.Get("ETag") == etag {
		t.Errorf("Atom and JSON representations share ETag %q", etag)
	}

	// The calendar is a third representation of the same feed, and the path is
	// a component of the validator, so it gets one of its own - and answers a
	// conditional GET on it.
	icsPath := strings.Replace(path, "feed.atom", "releases.ics", 1)
	icsResp, _ := watchFeedResponse(t, ts, icsPath)
	icsETag := icsResp.Header.Get("ETag")
	if icsETag == "" || icsETag == etag {
		t.Errorf("calendar ETag = %q, Atom ETag %q", icsETag, etag)
	}
	icsReq, err := http.NewRequest(http.MethodGet, ts.URL+icsPath, nil)
	if err != nil {
		t.Fatal(err)
	}
	icsReq.Header.Set("If-None-Match", icsETag)
	icsConditional, err := http.DefaultClient.Do(icsReq)
	if err != nil {
		t.Fatal(err)
	}
	defer func() { _ = icsConditional.Body.Close() }()
	if icsConditional.StatusCode != http.StatusNotModified {
		t.Errorf("conditional calendar status = %d, want 304", icsConditional.StatusCode)
	}
}

// TestWatchFeedETagMovesWithTheDay covers the one input to this body that no
// other cached surface has: the clock. The window is a rolling cutoff and a
// preorder becomes a release on a date, so a validator that named only the
// artifact would let a reader's conditional GET 304-renew yesterday's feed for
// as long as no new data release happened to be cut - losing exactly the news
// the feed exists to carry.
func TestWatchFeedETagMovesWithTheDay(t *testing.T) {
	cat := watchFeedCatalog()
	morning := time.Date(2026, 10, 20, 8, 0, 0, 0, time.UTC)
	srv, err := New(Config{
		DBPath:    buildFixtureDB(t, cat),
		SiteURL:   testSiteURL,
		swapGrace: time.Minute,
		now:       func() time.Time { return morning },
	})
	if err != nil {
		t.Fatal(err)
	}
	snap := srv.current()
	path := "/api/v1/watch/feed.atom"
	same := watchFeedETag(snap, testSiteURL, path, "the-stormlight-archive", "", morning.Add(9*time.Hour))
	first := watchFeedETag(snap, testSiteURL, path, "the-stormlight-archive", "", morning)
	if same != first {
		t.Errorf("ETag changed within one day: %q then %q", first, same)
	}
	next := watchFeedETag(snap, testSiteURL, path, "the-stormlight-archive", "", morning.AddDate(0, 0, 1))
	if next == first {
		t.Errorf("ETag %q did not move with the day", first)
	}
}

