func newWatchFeedServer(t *testing.T, cat *model.Catalog) (*Server, *httptest.Server) {
	t.Helper()
	srv, err := New(Config{
		DBPath:    buildFixtureDB(t, cat),
		SiteURL:   testSiteURL,
		swapGrace: time.Minute,
		now:       func() time.Time { return watchFeedNow },
	})
	if err != nil {
		t.Fatal(err)
	}
	ts := httptest.NewServer(srv.Handler())
	t.Cleanup(ts.Close)
	return srv, ts
}

func watchFeedResponse(t *testing.T, ts *httptest.Server, path string) (*http.Response, []byte) {
	t.Helper()
	resp, err := http.Get(ts.URL + path)
	if err != nil {
		t.Fatal(err)
	}
	defer func() { _ = resp.Body.Close() }()
	body, err := io.ReadAll(resp.Body)
	if err != nil {
		t.Fatal(err)
	}
	return resp, body
}

func TestWatchFeedGoldens(t *testing.T) {
	_, ts := newWatchFeedServer(t, watchFeedCatalog())
	for _, tc := range []struct {
		name        string
		path        string
		contentType string
	}{
		{"atom", "/api/v1/watch/feed.atom?s=the-stormlight-archive,not-here", "application/atom+xml; charset=utf-8"},
		{"json", "/api/v1/watch/feed.json?s=the-stormlight-archive,not-here", "application/feed+json; charset=utf-8"},
		{"ics", "/api/v1/watch/releases.ics?s=the-stormlight-archive,not-here", "text/calendar; charset=utf-8"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			resp, got := watchFeedResponse(t, ts, tc.path)
			if resp.StatusCode != http.StatusOK {
				t.Fatalf("status = %d, body %s", resp.StatusCode, got)
			}
			if ct := resp.Header.Get("Content-Type"); ct != tc.contentType {
				t.Errorf("Content-Type = %q, want %q", ct, tc.contentType)
			}
			if got := resp.Header.Get("Cache-Control"); got != watchFeedMaxAge {
				t.Errorf("Cache-Control = %q", got)
			}
			if got := resp.Header.Get("Access-Control-Allow-Origin"); got != "*" {
				t.Errorf("Access-Control-Allow-Origin = %q", got)
			}
			golden := filepath.Join("testdata", "golden", "watch-feed."+tc.name)
			// Regenerated by the same -update-golden flag as the entity pages
			// (html_test.go), for the same reason: a deliberate change to the
			// rendering shows up as a reviewable diff of the document itself.
			if *updateGolden {
				if err := os.WriteFile(golden, got, 0o644); err != nil {
					t.Fatal(err)
				}
				return
			}
			want, err := os.ReadFile(golden)
			if err != nil {
				t.Fatalf("read %s: %v (regenerate with -update-golden)\nrendered body:\n%s", golden, err, got)
			}
			if string(got) != string(want) {
				t.Errorf("rendered feed differs from %s (regenerate with -update-golden)\nrendered body:\n%s", golden, got)
			}
		})
	}
}

func TestWatchItemWindowAndDatePrecision(t *testing.T) {
	now := time.Date(2026, 9, 21, 15, 0, 0, 0, time.UTC)
	card := func(id, release, added string) *workCard {
		var addedAt *string
		if added != "" {
			addedAt = &added
		}
		return &workCard{ID: id, Title: id, ReleaseDate: release, AddedAt: addedAt}
	}
	cases := []struct {
		name    string
		card    *workCard
		keep    bool
		state   string
		updated string
	}{
		{"year uses first day", card("year", "2026", ""), false, "", ""},
		{"future month uses first day", card("month", "2026-10", ""), true, "preorder", "2026-10-01T00:00:00Z"},
		{"today is released", card("today", "2026-09-21", ""), true, "released", "2026-09-21T00:00:00Z"},
		{"release boundary included", card("boundary", "2026-06-23", ""), true, "released", "2026-06-23T00:00:00Z"},
		{"release before boundary excluded", card("old", "2026-06-22", ""), false, "", ""},
		{"unknown exact boundary included", card("unknown", "", "2026-06-23T15:00:00Z"), true, "date unknown", "2026-06-23T15:00:00Z"},
		{"unknown before boundary excluded", card("older-unknown", "", "2026-06-23T14:59:59Z"), false, "", ""},
		{"unknown date boundary included", card("unknown-date", "", "2026-06-23"), true, "date unknown", "2026-06-23T00:00:00Z"},
		// `date_flex` is a PATTERN, so a calendar-invalid value is schema-valid
		// and reaches the artifact. It must not delete the work from the feed:
		// the site renders it and lists the entry, so the feed falls through to
		// the added_at rule rather than disagreeing.
		{"calendar-invalid date falls through to added_at", card("bad-month", "2026-13", "2026-09-20"), true, "date unknown", "2026-09-20T00:00:00Z"},
		{"calendar-invalid date with no added_at is not news", card("bad-day", "2026-02-30", ""), false, "", ""},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			item, ok := watchItem("Series", seriesEntry{Position: "1", Work: tc.card}, 90, now, testSiteURL)
			if ok != tc.keep {
				t.Fatalf("keep = %v, want %v", ok, tc.keep)
			}
			if !ok {
				return
			}
			if item.state != tc.state || item.updated.Format(time.RFC3339) != tc.updated {
				t.Errorf("item state/time = %q %s, want %q %s", item.state, item.updated.Format(time.RFC3339), tc.state, tc.updated)
			}
		})
	}
	item, ok := watchItem("Series", seriesEntry{Work: card("unpositioned", "2026-10", "")}, 90, now, testSiteURL)
	if !ok || item.title != "Series: unpositioned" {
		t.Errorf("unpositioned title = %q, keep %v", item.title, ok)
	}
}

// TestReleaseDatePrecisionMirrorsTheSite pins the Go half of the hand-mirrored
// twin in site/src/lib/dates.ts against the SAME cases site/src/lib/dates.test.ts
// pins the TS half against. A reader comparing their /watching list with this
// feed sees two renderings of one catalogue value, so "is it still ahead" and
// "how does it read" must answer identically on both sides - and neither may
// invent precision the catalogue did not state.
func TestReleaseDatePrecisionMirrorsTheSite(t *testing.T) {
	// dates.test.ts's `today`.
	now := time.Date(2026, 9, 21, 15, 0, 0, 0, time.UTC)
	for _, tc := range []struct {
		value  string
		future bool
		reads  string
	}{
		{"2026-09-22", true, "22 Sep 2026"},
		{"2026-09-21", false, "21 Sep 2026"}, // out today: available
		{"2026-09-20", false, "20 Sep 2026"},
		{"2026-10", true, "Oct 2026"}, // a month, never a made-up day
		{"2026-09", false, "Sep 2026"},
		{"2026-08", false, "Aug 2026"},
		// The case that decides the rule: widening "2026" to 1 January would
		// call a book published in March a preorder for the rest of the year.
		{"2026", false, "2026"},
		{"2027", true, "2027"},
		{"2025", false, "2025"},
		{"2026-01-05", false, "5 Jan 2026"}, // no leading zero on a day
	} {
		t.Run(tc.value, func(t *testing.T) {
			parsed, ok := parseReleaseDate(tc.value)
			if !ok {
				t.Fatalf("parseReleaseDate(%q) rejected a stated value", tc.value)
			}
			if got := releaseIsFuture(tc.value, now); got != tc.future {
				t.Errorf("releaseIsFuture(%q) = %v, want %v", tc.value, got, tc.future)
			}
			if got := formatReleaseDate(tc.value, parsed); got != tc.reads {
				t.Errorf("formatReleaseDate(%q) = %q, want %q", tc.value, got, tc.reads)
			}
		})
	}
	// An unparseable value is never a preorder on either side; here it never
	// becomes an item at all, because Atom needs a timestamp for it.
	for _, bad := range []string{"", "next spring", "2026-10-20T00:00:00Z"} {
		if _, ok := parseReleaseDate(bad); ok {
			t.Errorf("parseReleaseDate(%q) accepted an unparseable value", bad)
		}
		if releaseIsFuture(bad, now) {
			t.Errorf("releaseIsFuture(%q) called an unparseable value a preorder", bad)
		}
	}
}

